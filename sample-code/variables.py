# variable: a name for some data stored in memory 

# my_name is a variable/name
# = is the assignment operator
# 'Stuart' is a value/data/string literal
my_name = 'Stuart'

# reassignment; the variable is changed, not the data
my_name = 'Bailey, Stuart'

# other_name refs the same object as does my_name
# other_name --> 'Bailey, Stuart' <-- my_name
other_name = my_name

# constant: a name that cannot be reassigned 
# Python doesn't have constants but...
# if you name your variable in SHOUTY_CASE it is assumed to be a constant
